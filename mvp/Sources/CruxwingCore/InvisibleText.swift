import Foundation

/// Знаки, которых человек не видит, а модель читает.
///
/// Жил в `BundledSkillSanitizer` — то есть стоял у входа для встроенных
/// методичек, про корпус которых там же написано «сегодня чист». Враждебное
/// ходит другим входом: заголовок задачи в чужом трекере, страница вики,
/// расшифровка от Fireflies — сервиса, который продаёт конкурирующий продукт.
/// Поэтому чистка вынесена сюда и зовётся со ВСЕХ входов.
///
/// Входов теперь три, и третий — не в запрос, а прямо на экран: слова
/// чужого сервиса при отказе показываются человеку (`VendorText`). Ради
/// него чистка и переехала в ядро: держать две одинаковые — значит
/// однажды починить одну.
///
/// Важен и порядок: чистка идёт ДО проверки на внедрение. Блок Unicode Tags
/// повторяет ASCII один в один и не отображается ничем, поэтому «ignore all
/// previous instructions», записанное тегами, для сторожа выглядит пустотой.
/// После чистки это обычная строка, и сторож её видит.
public enum InvisibleText {

    /// Убрать невидимые и переворачивающие знаки.
    ///
    /// Список намеренно узкий: убирается то, что нельзя увидеть или что меняет
    /// порядок чтения, и не трогается ничего, что человек мог написать сам.
    /// Неразрывный пробел, тире и «ё» — обычный текст встречи, а не атака.
    public static func strip(_ text: String) -> String {
        String(text.unicodeScalars.filter { scalar in
            switch scalar.value {
            case 0x00AD:                            // мягкий перенос
                return false
            case 0x061C:                            // арабская метка буквы
                return false
            case 0x180E:                            // монгольский разделитель
                return false
            case 0x200B, 0x200C, 0x200D:            // нулевой ширины: пробел, не-соединитель, соединитель
                return false
            case 0x200E, 0x200F:                    // метки направления
                return false
            case 0x2060...0x2064:                   // соединитель слов и невидимые операторы
                return false
            case 0xFEFF:                            // метка порядка байтов
                return false
            case 0x202A...0x202E, 0x2066...0x2069:  // перевороты и изоляты направления
                return false
            case 0xE0000...0xE007F:                 // Unicode Tags — невидимый ASCII
                return false
            case 0xFFF9...0xFFFB:                   // знаки межстрочных примечаний
                return false
            default:
                return true
            }
        })
    }

    /// Вернуть невидимому ASCII его вид — ТОЛЬКО для проверки, не для запроса.
    ///
    /// Блок Unicode Tags повторяет ASCII один в один: «ignore all previous
    /// instructions», записанное там, не отображается ничем, и сторож,
    /// сравнивающий строки, не видит в нём ни одной буквы. Развернув блок
    /// обратно, сторож наконец видит попытку.
    ///
    /// В запрос эта строка не уезжает никогда: там текст ЧИЩЕНЫЙ, иначе мы
    /// сами вписали бы спрятанное указание в запрос обычными буквами.
    public static func unmaskTags(_ text: String) -> String {
        String(String.UnicodeScalarView(text.unicodeScalars.map { scalar in
            (0xE0000...0xE007F).contains(scalar.value)
                ? (Unicode.Scalar(scalar.value - 0xE0000) ?? scalar)
                : scalar
        }))
    }
}
