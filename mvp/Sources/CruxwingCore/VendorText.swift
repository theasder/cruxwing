import Foundation

/// Слова чужого сервиса, показанные человеку.
///
/// Отказ передаётся его собственными словами, и это правильно: «сервис ответил
/// ошибкой 400» отправляет чинить не то, а «поле queue обязательно» чинит.
/// Но слова эти пишет тот, у кого свои интересы, и попадают они на экран в
/// самый послушный момент: человек только что получил отказ и готов идти
/// исправлять.
///
/// Отсюда три правила, и ни одно не про содержание — содержание мы не судим.
///
/// 1. **Одной строкой.** Переносы позволяют дорисовать в нашем окне что угодно
///    похожее на наш же интерфейс, вплоть до отдельной строчки-«подсказки».
/// 2. **Коротко.** Длина не ограничивалась вовсе, и стена текста от сервиса
///    вытесняет с экрана всё, что написали мы, — включая приписку о том, чьи
///    это слова.
/// 3. **Без невидимых знаков.** Блок Unicode Tags повторяет ASCII один в один
///    и не отображается ничем: внутри пустой на вид строки помещается абзац.
///    Ту же чистку проходят находки коннекторов на входе в запрос — здесь
///    дверь на экран, и она была открыта.
///
/// Что НЕ делается: адрес из текста не вырезается. Продукт обещает показывать
/// источник, а не прятать его, и человек, видящий адрес целиком, судит о нём
/// сам. Прятать надо не адрес, а его подмену — этим занят `VendorLink` на
/// стороне приложения.
public enum VendorText {
    /// Сколько слов сервиса помещается на экран рядом с нашими.
    public static let limit = 160

    /// Сколько знаков бывает у имени. Больше — это уже не имя.
    public static let nameLimit = 40

    /// Имя говорящего, пришедшее от чужого сервиса.
    ///
    /// Приписка «кто это сказал» — не украшение записи, а сам продукт: он
    /// отвечает на «кто что решил». Пишет её здесь Fireflies — сервис, который
    /// продаёт конкурирующий продукт, — и пишет про ЧУЖУЮ встречу, свою же
    /// расшифровку которой он и отдаёт.
    ///
    /// Правило то же, что у прочих слов сервиса: одна строка, без невидимых
    /// знаков, с пределом. Но предел здесь не обрезает, а ОТКАЗЫВАЕТ: имя
    /// длиной в абзац — не длинное имя, а что-то другое, и обрезок от него
    /// («Артём Дремов, согласовал по…») выглядел бы как настоящее имя, которого
    /// никто не носит. Нет имени — лучше, чем выдуманное: строка останется без
    /// приписки, и это честно.
    ///
    /// Чего это правило НЕ делает: не мешает сервису назвать говорящего чужим
    /// именем. Он отдаёт расшифровку целиком, и различить подмену нечем — но
    /// подмена помещается в сорок знаков и одну строку, а разметка экрана и
    /// спрятанный абзац указаний — нет.
    public static func speakerName(_ raw: String) -> String? {
        let clean = forPerson(raw)
        guard !clean.isEmpty, clean.count <= nameLimit,
              clean.contains(where: { $0.isLetter || $0.isNumber }) else { return nil }
        return clean
    }

    public static func forPerson(_ raw: String) -> String {
        let flat = InvisibleText.strip(raw)
            .replacingOccurrences(of: "\r\n", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
        let collapsed = flat.split(separator: " ", omittingEmptySubsequences: true)
            .joined(separator: " ")
        guard collapsed.count > limit else { return collapsed }
        return String(collapsed.prefix(limit)) + "…"
    }
}
