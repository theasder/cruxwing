import Foundation

/// Сравнивает ли этот сервис строки побайтово.
///
/// Измерено на живых установках 2026-08-19: Redmine и Nextcloud с базой по
/// умолчанию (SQLite) не приводят кириллицу к одному регистру, и «тарифы» не
/// находит «Тарифы». Расшифровка отдаёт слова строчными, поэтому половина
/// ответов пропадала.
///
/// Повтор на пустой выдаче закрыл только полную потерю. Частичную он не ловит:
/// Redmine на «тарифы» отдаёт одну задачу из двух, и отсюда одна находка
/// неотличима от всех. Ждать пустоты бесполезно — у такого сервиса её может не
/// быть никогда.
///
/// Поэтому спрашиваем дважды ОДИН раз на сервис и запоминаем ответ. Совпали
/// выдачи — регистр сервис приводит сам, больше не переспрашиваем. Разошлись —
/// сравнивает байты, и дальше спрашиваем оба написания всегда. Цена знания:
/// один лишний запрос на сервис за запуск. Цена незнания: половина ответов.
public actor ConnectorCaseMemory {

    public enum Behaviour: Sendable {
        /// Ещё не спрашивали дважды — или спросили, и обе выдачи были пусты:
        /// из двух пустых ничего не следует.
        case unknown
        /// Регистр приводит сама база: второе написание ничего не добавляет.
        case foldsCase
        /// Сравнивает байты: второе написание приносит другие ответы.
        case comparesBytes
    }

    public static let shared = ConnectorCaseMemory()

    private var known: [String: Behaviour] = [:]

    public init() {}

    private func key(_ service: String, _ host: String?) -> String {
        "\(service)|\(host ?? "")"
    }

    /// Сервисы, попросившие обращаться реже.
    ///
    /// Второе написание удваивает запросы к тому, кто уже сказал «реже». Свой
    /// же комментарий про кэш: троттлинг, на который потом жалуются, отчасти
    /// наш собственный.
    ///
    /// Недружелюбному сервису это ещё и рычаг: достаточно отвечать на два
    /// написания по-разному — и мы сами удвоим ему нагрузку, после чего он
    /// придушит нас на законных основаниях. Различить это и SQLite нечем, а
    /// вот перестать давить, когда просят, можно.
    private var askedToSlowDown: Set<String> = []

    public func behaviour(service: String, host: String?) -> Behaviour {
        // Просьба подождать сильнее знания: пока сервис душит, второе написание
        // не спрашиваем, даже зная, что он сравнивает байты. Половина ответов
        // лучше, чем ответ «сервис просит обращаться реже».
        if askedToSlowDown.contains(key(service, host)) { return .foldsCase }
        return known[key(service, host)] ?? .unknown
    }

    /// Сервис попросил обращаться реже — перестаём спрашивать вторым написанием.
    public func slowDown(service: String, host: String?) {
        askedToSlowDown.insert(key(service, host))
    }

    /// Знает ли память, что сервис просил подождать.
    public func isSlowedDown(service: String, host: String?) -> Bool {
        askedToSlowDown.contains(key(service, host))
    }

    /// Ищет ли этот сервис по началу слова.
    ///
    /// Вопрос основой помогает не везде, и это измерено, а не предположено.
    /// BookStack и Redmine ищут по вхождению, и «тариф» находит «тарифами».
    /// Gitea сравнивает слова целиком: на живой установке 2026-08-19 «тарифы»
    /// нашли две задачи, а «тариф» — НОЛЬ. Там вопрос основой — чистая трата
    /// чужого сервера.
    ///
    /// Признак однозначный: основа короче слова, значит по вхождению она
    /// нашла бы не меньше. Вернулась пустота там, где слово целиком что-то
    /// нашло, — сервис ищет словами. Из двух пустых, как и с регистром, не
    /// следует ничего.
    ///
    /// Вывод делается со ВТОРОГО раза, а не с первого, и цена ошибки тут
    /// несимметрична. Ошиблись в сторону осторожности — один лишний запрос за
    /// звонок к сервису, который всё равно ничего не найдёт. Ошиблись в другую
    /// — русские склонения перестают находиться у этого сервиса до конца
    /// работы программы, и человеку об этом не скажет никто.
    ///
    /// А поводов ошибиться хватает и без злого умысла: индекс перестраивается,
    /// сервис отвечает пустотой на переключении, запрос попал в мгновение между
    /// записью и индексацией. Одна пустота — это не измерение.
    ///
    /// Недружелюбному сервису это ещё и рычаг, дешёвый и незаметный: ответить
    /// на слово находками, а на основу пустотой — и мы сами выключим у себя
    /// поиск по склонениям. Отличить такой ответ от честного нечем (Gitea
    /// отвечает точно так же и по-честному), но потребовать ДВА совпадающих
    /// наблюдения можно, и это удваивает цену рычага, ничего не ломая.
    private var ignoresStems: Set<String> = []
    /// Сколько раз подряд основа возвращала пустоту там, где слово нашло.
    private var stemMisses: [String: Int] = [:]

    public func stemsAreUseless(service: String, host: String?) -> Bool {
        ignoresStems.contains(key(service, host))
    }

    public func learnStemIsUseless(service: String, host: String?) {
        let key = key(service, host)
        let seen = (stemMisses[key] ?? 0) + 1
        stemMisses[key] = seen
        if seen >= 2 { ignoresStems.insert(key) }
    }

    /// Основа что-то нашла — значит прошлая пустота была случайностью.
    ///
    /// Без этого два промаха за неделю, разделённые сотней удачных вопросов,
    /// значили бы то же, что два подряд. Счётчик обнуляется на первом же
    /// доказательстве обратного.
    public func learnStemWorks(service: String, host: String?) {
        stemMisses[key(service, host)] = 0
    }

    /// Забыть всё. Нужно наборам: память общая на процесс, и без этого
    /// соседние проверки начинают зависеть от порядка — общий кэш однажды уже
    /// переносил ответы между наборами, идущими рядом.
    public func forget() {
        known.removeAll(); askedToSlowDown.removeAll()
        ignoresStems.removeAll(); stemMisses.removeAll()
    }

    public func learn(_ behaviour: Behaviour, service: String, host: String?) {
        guard behaviour != .unknown else { return }
        known[key(service, host)] = behaviour
    }
}
