#!/usr/bin/env bash
# Прогон собранной программы, а не исходников.
#
# Зачем отдельно от `swift test`. Набор проверяет функции; здесь проверяется то,
# что человек запускает: собранный двоичный файл, настоящие аргументы, настоящий
# вывод. 2026-08-18 такой прогон нашёл то, чего не видел ни один тест: команда
# `записать` печатала «Записываю 5 с. Говорите…» и только потом сообщала, что
# записи на этой системе нет вовсе. Функция вела себя правильно, программа — нет.
#
# Работает на любой системе; на macOS микрофон есть, поэтому последняя проверка
# там пропускается с указанной причиной.
set -euo pipefail

cd "$(dirname "$0")/.."

BIN="$(swift build --package-path mvp -c release --show-bin-path)/orakul"
[ -x "$BIN" ] || { echo "нет собранной программы: $BIN"; exit 1; }

WORK="$(mktemp -d)"
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT
export ORAKUL_HOME="$WORK/архив"

TRANSCRIPT="$WORK/расшифровка.txt"
printf 'Аня: По тарифам решили поднять месячный на пятнадцать процентов.\nБорис: Я выкачу к пятнице.\n' > "$TRANSCRIPT"

say()  { printf '  %s\n' "$1"; }
fail() { printf 'НЕ ТАК: %s\n' "$1"; exit 1; }

echo "== добавить =="
OUT="$("$BIN" добавить "$TRANSCRIPT" "Планёрка по тарифам")"
say "$OUT"
case "$OUT" in *"Добавлено"*) ;; *) fail "звонок не добавился" ;; esac

echo "== найти: отвечает словами из расшифровки =="
OUT="$("$BIN" найти что решили по тарифам)"
say "$OUT"
case "$OUT" in *"пятнадцать процентов"*) ;; *) fail "ответ не цитирует расшифровку" ;; esac

echo "== найти: отказ вместо выдумки =="
OUT="$("$BIN" найти когда корпоратив)"
say "$OUT"
case "$OUT" in *"придумывать не буду"*) ;; *) fail "выдумал ответ вместо отказа" ;; esac

echo "== опечатка отличается от отсутствия разговора =="
OUT="$("$BIN" найти тарифф)"
say "$OUT"
case "$OUT" in *"опечатк"*) ;; *) fail "опечатка не отличена от «не говорили»" ;; esac

echo "== запись с микрофона: где её нет, приглашения говорить быть не должно =="
if [ "$(uname)" = "Darwin" ]; then
  say "пропущено: на macOS микрофон есть, и проверять нечего"
else
  set +e
  OUT="$("$BIN" записать 5 "Проба" 2>&1)"
  CODE=$?
  set -e
  say "$OUT"
  [ "$CODE" -eq 0 ] && fail "отказ ушёл с нулевым кодом возврата"
  case "$OUT" in *"Говорите"*) fail "человека позвали говорить в микрофон, которого нет" ;; esac
  case "$OUT" in *"не работает"*) ;; *) fail "отказ не объяснён" ;; esac
fi

echo "всё сошлось"
