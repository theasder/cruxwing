#!/usr/bin/env bash
# Проверяет корпус русской речи перед тем, как по нему что-то мерить.
#
#   bash scripts/corpus-check.sh /путь/к/корпусу
#
# Зачем отдельная команда. Корпус собирает один человек, а замер по нему делает
# другой, и «у меня всё сошлось» между ними не передаётся. Ошибка в описании не
# роняет замер — она молча уменьшает корпус: запись, чей файл не нашёлся,
# выпадает, среднее считается по остатку и выглядит убедительно.
set -euo pipefail

DIR="${1:-}"
[ -n "$DIR" ] || { echo "нужен путь: bash scripts/corpus-check.sh /путь/к/корпусу" >&2; exit 2; }
ROOT="$(cd "$(dirname "$0")/.." && pwd)"

# Разбор и проверки — те же, что у замера: второй набор правил разошёлся бы с
# первым, и «проверено» перестало бы что-то значить.
swift run --package-path "$ROOT/mvp" orakul корпус "$DIR"
