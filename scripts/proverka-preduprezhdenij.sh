#!/usr/bin/env bash
# Предупреждения, которые нельзя не заметить.
#
# 2026-08-20: признак обращения к модели вычислялся при подготовке записи и
# никуда не передавался, поэтому предупреждение в окне подтверждения не
# показывалось ни разу. Компилятор об этом СКАЗАЛ:
#
#   warning: initialization of immutable value 'signal' was never used
#
# Строка проехала мимо: сборка печатает сотни строк, и предупреждение среди них
# выглядит как шум. Здесь перечислены те виды, которых быть не должно вовсе, —
# и прогон падает, если они появились.
#
# Список короткий намеренно. Запрет всех предупреждений сразу означал бы, что
# первым же делом кто-то отключит проверку целиком: сегодня в наборах есть
# четыре «mutation of captured var» и пара «no async operations», и они
# разбираются отдельно, а не под угрозой красного прогона.
set -euo pipefail
cd "$(dirname "$0")/.."

# Виды, которые прячут дефект: вычисленное и выброшенное значение.
FATAL='was never used|result of call to .* is unused'

OUT=$(mktemp)
trap 'rm -f "$OUT"' EXIT

# `grep -c` возвращает 1, когда совпадений нет, и под `set -e` это убивает
# скрипт на самом хорошем исходе — ноль предупреждений.
count() { grep -c "warning:" "$1" 2>/dev/null || true; }

# Каждый пакет собирается РОВНО ОДИН РАЗ.
#
# Первая версия строила ядро дважды: сначала в общий журнал, потом отдельно для
# порога «ноль». Второй прогон был пошаговым и молчал, поэтому вернувшееся
# предупреждение уходило в первый журнал, а проверка порога смотрела во второй и
# ничего не находила. Проверено мутацией — тогда она и не сработала.
CORE=$(mktemp)
trap 'rm -f "$OUT" "$CORE"' EXIT

# Пересборка вынуждается: иначе проверяется не код, а список того, что
# случайно изменилось с прошлого раза. Пошаговая сборка молчит, и порог «ноль»
# выполняется сам собой — именно так эта проверка один раз и «прошла».
# Цена — пара минут; она платится один раз перед отправкой, а не на каждое
# сохранение.
touch_sources() { find "$1" -name "*.swift" -exec touch {} +; }

echo ">> сборка ядра с наборами"
touch_sources mvp/Sources; touch_sources mvp/Tests
swift build --package-path mvp --build-tests 2>&1 > "$CORE"
cat "$CORE" >> "$OUT"
echo "   предупреждений: $(count "$CORE")"

echo ">> сборка приложения"
touch_sources app/Sources
swift build --package-path app 2>&1 | tee -a "$OUT" >/dev/null
echo "   всего предупреждений: $(count "$OUT")"

# Сборка бывает пошаговой: если ничего не менялось, компилятор молчит и
# проверять нечего. Молчание при этом не доказательство — о нём говорится вслух.
if ! grep -q "Compiling\|Building for" "$OUT"; then
  echo ">> ничего не пересобиралось: предупреждений не видно, но и не проверено"
fi

# Совпадение ищется В СТРОКЕ, а не сразу после «warning:». Первая версия
# требовала «warning: was never used», а компилятор пишет «warning:
# initialization of immutable value 'signal' was never used» — и проверка
# пропустила ровно тот дефект, ради которого написана.
# У ядра порог другой — ноль. 2026-08-21 оно приведено к нулю целиком
# (захваченные переменные в наборах заменены на Recorder/Flag/SyncCounter,
# лишний await убран), и держать ноль там, где он достигнут, дешевле, чем
# возвращаться к разбору списка через месяц. У приложения так нельзя: там 52
# места, из них 45 — один устаревший вызов SwiftUI, и красный прогон на этом
# означал бы отключённую проверку.
CORE_WARNINGS=$(count "$CORE")
if [ "${CORE_WARNINGS:-0}" != "0" ]; then
  grep -n "warning:" "$CORE" >&2 | head -5
  echo "!! в ядре снова есть предупреждения ($CORE_WARNINGS): там держится ноль" >&2
  exit 1
fi
echo ">> ядро: предупреждений нет"

# У приложения свой порог — не ноль, а «не больше, чем было».
#
# 2026-08-21 их было шесть: четыре про NSLock внутри async-функции и два про
# изоляцию главного актора. Пять убраны, осталось одно, названное в
# SamplePlayback. Ноль требовать нельзя — сорок пять устаревших вызовов SwiftUI
# рядом, и красный прогон на них означал бы отключённую проверку. А вот расти
# этому числу незачем: каждое такое место — файл, который не соберётся на языке
# Swift 6.
APP_FATAL_LIMIT=1
APP_FATAL=$(grep -c "error in the Swift 6 language mode" "$OUT" 2>/dev/null || true)
# Одно и то же предупреждение печатается на каждую единицу компиляции, поэтому
# считаются РАЗНЫЕ места, а не строки.
APP_FATAL=$(grep -oE "[A-Za-z]+\.swift:[0-9]+:[0-9]+: warning: .*error in the Swift 6" "$OUT" \
            | sort -u | wc -l | tr -d ' ')
if [ "${APP_FATAL:-0}" -gt "$APP_FATAL_LIMIT" ]; then
  grep -oE "[A-Za-z]+\.swift:[0-9]+:[0-9]+: warning: .*error in the Swift 6" "$OUT" | sort -u >&2
  echo "!! мест, которые не соберутся на Swift 6: ${APP_FATAL} (было ${APP_FATAL_LIMIT})" >&2
  exit 1
fi
echo ">> приложение: мест, смертельных для Swift 6, — ${APP_FATAL:-0} из ${APP_FATAL_LIMIT} допустимых"

if grep -nE "warning:.*($FATAL)" "$OUT" >&2; then
  echo "!! вычисленное значение выброшено — именно так пропало предупреждение о внедрении" >&2
  exit 1
fi
echo ">> запрещённых предупреждений нет"
