#!/usr/bin/env bash
# Снимок меток репозитория для проверки, которая не ходит в сеть.
#
# GitHub молча выбрасывает метку, которой нет: форма отправляется, отчёт
# приходит без метки, и всё выглядит сработавшим. Именно так метка `ошибка`
# полгода не существовала, а `oshibka.yml` её объявлял.
#
# Прогон без сети должен уметь ловить это же. Значит нужен снимок, и снимок
# обязан быть снят с живого репозитория, а не написан от руки — иначе он
# станет вторым источником правды и разойдётся молча, как и метка.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "# Снят $(date +%F) командой scripts/snimok-metok.sh — руками не править."
  echo "# Метки, которые есть в репозитории на самом деле."
  gh label list --limit 200 | cut -f1
} > .github/metki.txt
echo ">> $(grep -vc '^#' .github/metki.txt) меток записано в .github/metki.txt"
