import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

// Живая проба знает свои сервисы в ТРЁХ местах, и они обязаны совпадать.
//
//   1. `case` — что скрипт соглашается принять;
//   2. строка «Использование» — что он называет человеку;
//   3. сами ветки `[ "$SERVICE" = … ]` — что он на самом деле умеет.
//
// Расходятся они молча и по-разному. Ветка, не внесённая в `case`, отвергается
// раньше, чем до неё дойдут: код есть, поднять сервис нельзя, и выглядит это
// как «проба не работает». Сервис, забытый в строке использования, существует и
// не назван — человек про него не узнает. А имя в списке без ветки поднимет
// сервис, который никто не наполнял, и проба скажет «ничего не нашлось» про
// пустую установку.
//
// Ошибку эту я уже совершил: ветка называлась `rocketchat`, а сервис зовётся
// `rocketChat`. Сервер поднялся, наполнился и не нашёлся.

const script = readFileSync('scripts/zhivaya-proba.sh', 'utf8');

function accepted() {
  const m = /^\s{2}([a-zA-Z|]+)\)\s;;/m.exec(script);
  assert.ok(m, 'в скрипте не нашёлся список принимаемых сервисов');
  return m[1].split('|');
}

function announced() {
  const m = /Использование: \$0 ([a-zA-Z|]+)/.exec(script);
  assert.ok(m, 'в скрипте не нашлась строка использования');
  return m[1].split('|');
}

function implemented() {
  return [...script.matchAll(/\[ "\$SERVICE" = ([a-zA-Z]+) \]; then/g)].map((m) => m[1]);
}

test('принимаемые, названные и написанные сервисы — один список', () => {
  const a = accepted().sort();
  const b = announced().sort();
  const c = implemented().sort();

  assert.ok(a.length >= 5, `принимаемых сервисов ${a.length} — разбор сломан`);
  assert.deepEqual(b, a, 'строка использования разошлась с тем, что скрипт принимает');
  assert.deepEqual(c, a, 'ветки скрипта разошлись с тем, что он принимает');
});

test('освобождённые от проверки косвенной формы — настоящие сервисы', () => {
  // Список освобождённых — тоже второй список, и опечатка в нём не заметна
  // ничем: сервис просто перестаёт быть освобождённым или, наоборот, никогда
  // им не станет.
  const m = /^\s{2}([a-zA-Z|]+)\) STEM_EXPECTED=0/m.exec(script);
  assert.ok(m, 'не нашёлся список освобождённых от проверки основой');
  const exempt = m[1].split('|');
  assert.ok(exempt.length >= 2, `освобождённых ${exempt.length} — разбор сломан`);
  for (const name of exempt) {
    assert.ok(accepted().includes(name),
      `«${name}» освобождён от проверки основой, а такого сервиса у пробы нет`);
  }
});
